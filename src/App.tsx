import React, { useState, useMemo, useEffect } from 'react';
import {
  VendorPriceRecord,
  EventBrief,
  TimelineTask,
  ApprovalAction,
} from './types/intelligence';
import { GeneratedEventPlan, PlanApprovalResponse } from './types/planning';
import { calculateLedgerSummary, formatInr } from './utils/ledgerMath';
import { mapPlanToLedger } from './utils/planMapper';
import { refineEventPlanApi } from './services/assistantApi';
import {
  SAMPLE_BRIEFS,
  SAMPLE_VENDOR_BATCH,
  SAMPLE_TASKS_BATCH,
  SAMPLE_APPROVALS_BATCH,
} from './utils/samplePayloads';

// Components
import { Header } from './components/Header';
import { AgentChatPanel } from './components/AgentChatPanel';
import { GlobalMetricsBar } from './components/GlobalMetricsBar';
import { VendorLedgerTable } from './components/VendorLedgerTable';
import { RecordInjectorModal } from './components/RecordInjectorModal';
import { VerbatimAuditDrawer } from './components/VerbatimAuditDrawer';
import { ApprovalQueuePanel } from './components/ApprovalQueuePanel';
import { TimelineTasksPanel } from './components/TimelineTasksPanel';
import { DeterministicScenarioSummary } from './components/DeterministicScenarioSummary';
import { CommandPalette } from './components/CommandPalette';
import { ExportLedgerModal } from './components/ExportLedgerModal';
import { StructuredPlanPreview } from './components/StructuredPlanPreview';
import { GuidedPlanningWizard } from './components/GuidedPlanningWizard';
import { VendorDirectoryPanel } from './components/VendorDirectoryPanel';
import { ExternalIntelligencePanel } from './components/ExternalIntelligencePanel';

import {
  Layers,
  PieChart,
  ListTodo,
  CheckCircle2,
  Sparkles,
  ArrowRight,
  Wand2,
  FileText,
  Bot,
  Building2,
} from 'lucide-react';

export const App: React.FC = () => {
  // Application State
  const [vendors, setVendors] = useState<VendorPriceRecord[]>([]);
  const [tasks, setTasks] = useState<TimelineTask[]>([]);
  const [pendingApprovals, setPendingApprovals] = useState<ApprovalAction[]>([]);
  const [brief, setBrief] = useState<EventBrief | null>(null);
  const [structuredPlan, setStructuredPlan] = useState<GeneratedEventPlan | null>(null);

  // View Mode: 'split' | 'chat' | 'wizard' | 'plan' | 'vendors' | 'external'
  const [viewMode, setViewMode] = useState<'split' | 'chat' | 'wizard' | 'plan' | 'vendors' | 'external'>('split');

  // Plan View Sub-Tab: 'structured' | 'quotes' | 'vendors' | 'breakdown' | 'checklist'
  const [activePlanTab, setActivePlanTab] = useState<'structured' | 'quotes' | 'vendors' | 'breakdown' | 'checklist'>('structured');

  // Modal & Drawer State
  const [isInjectorOpen, setIsInjectorOpen] = useState(false);
  const [isExportOpen, setIsExportOpen] = useState(false);
  const [isCommandPaletteOpen, setIsCommandPaletteOpen] = useState(false);
  const [auditingVendor, setAuditingVendor] = useState<VendorPriceRecord | null>(null);
  const [isRefining, setIsRefining] = useState(false);
  const [committedApproval, setCommittedApproval] = useState<PlanApprovalResponse | null>(null);

  // Friendly Toast Notification
  const [toastMessage, setToastMessage] = useState<string | null>(null);

  const showToast = (msg: string) => {
    setToastMessage(msg);
    setTimeout(() => {
      setToastMessage(null);
    }, 3200);
  };

  const handlePlanApproved = (res: PlanApprovalResponse) => {
    setCommittedApproval(res);
    showToast(`Plan approved & committed! Event ID: ${res.event_id.substring(0, 8)}...`);
  };

  // Keyboard Shortcuts (Cmd+K / Ctrl+K)
  useEffect(() => {
    const handleGlobalKeyDown = (e: KeyboardEvent) => {
      const target = e.target as HTMLElement;
      if (['INPUT', 'TEXTAREA', 'SELECT'].includes(target.tagName)) return;

      if ((e.metaKey || e.ctrlKey) && e.key.toLowerCase() === 'k') {
        e.preventDefault();
        setIsCommandPaletteOpen((prev) => !prev);
      }
    };

    window.addEventListener('keydown', handleGlobalKeyDown);
    return () => window.removeEventListener('keydown', handleGlobalKeyDown);
  }, []);

  // Live Summary Calculation
  const summary = useMemo(() => {
    const defaultBrief: EventBrief = brief || {
      eventName: 'My Event',
      location: 'Bengaluru, India',
      eventDate: '2026-11-20',
      guestCount: 150,
      durationDays: 1,
      durationHours: 8,
      targetBudgetInr: 1000000,
      contingencyPct: 10,
    };
    return calculateLedgerSummary(vendors, defaultBrief);
  }, [vendors, brief]);

  // Handler when a Structured Plan is generated by AI (Chat or Wizard)
  const handleStructuredPlanGenerated = (plan: GeneratedEventPlan) => {
    setStructuredPlan(plan);
    const mapped = mapPlanToLedger(plan);
    setBrief(mapped.brief);
    setVendors(mapped.vendors);
    setTasks(mapped.tasks);
    setPendingApprovals(mapped.approvals);
    setActivePlanTab('structured');
    showToast(`Synthesized plan for "${plan.brief.event_name}" (${formatInr(plan.budget_proposal.total_allocated)})!`);
  };

  // Handler to update the structured plan from user edits
  const handleUpdateStructuredPlan = (updatedPlan: GeneratedEventPlan) => {
    setStructuredPlan(updatedPlan);
    const mapped = mapPlanToLedger(updatedPlan);
    setBrief(mapped.brief);
    showToast('Plan draft updated locally.');
  };

  // Handler when user triggers AI refinement from the preview card
  const handleRefineStructuredPlan = async (instructions: string) => {
    if (!structuredPlan) return;
    setIsRefining(true);
    try {
      const refined = await refineEventPlanApi({
        existing_plan: structuredPlan,
        refinement_instructions: instructions,
      });
      setStructuredPlan(refined);
      const mapped = mapPlanToLedger(refined);
      setBrief(mapped.brief);
      setVendors(mapped.vendors);
      setTasks(mapped.tasks);
      setPendingApprovals(mapped.approvals);
      showToast(`Refined: "${instructions.slice(0, 32)}..."`);
    } catch (err: any) {
      showToast(`Refinement failed: ${err.message || 'Error'}`);
      throw err;
    } finally {
      setIsRefining(false);
    }
  };

  // Handler when AI Agent completes an execution
  const handlePlanGenerated = (result: {
    brief: EventBrief;
    vendors: VendorPriceRecord[];
    tasks: TimelineTask[];
    approvals: ApprovalAction[];
  }) => {
    setBrief(result.brief);
    setVendors(result.vendors);
    setTasks(result.tasks);
    setPendingApprovals(result.approvals);
  };

  // Handlers for Vendor Records
  const handleInjectRecords = (newRecords: VendorPriceRecord[]) => {
    setVendors((prev) => [...prev, ...newRecords]);
    showToast(`Added ${newRecords.length} vendor${newRecords.length === 1 ? '' : 's'} to your budget.`);
  };

  const handleToggleSelectVendor = (vendorId: string) => {
    setVendors((prev) =>
      prev.map((v) =>
        v.id === vendorId ? { ...v, isSelectedForBudget: !v.isSelectedForBudget } : v
      )
    );
  };

  const handleSelectAllVendors = (select: boolean) => {
    setVendors((prev) =>
      prev.map((v) => ({ ...v, isSelectedForBudget: select }))
    );
  };

  const handleDeleteVendor = (vendorId: string) => {
    setVendors((prev) => prev.filter((v) => v.id !== vendorId));
    showToast('Vendor removed.');
  };

  // Handlers for Approvals / Inquiries
  const handleApproveAction = (id: string) => {
    setPendingApprovals((prev) =>
      prev.map((a) => (a.id === id ? { ...a, status: 'approved' } : a))
    );
    showToast('Inquiry marked as sent.');
  };

  const handleRejectAction = (id: string) => {
    setPendingApprovals((prev) =>
      prev.map((a) => (a.id === id ? { ...a, status: 'rejected' } : a))
    );
    showToast('Inquiry dismissed.');
  };

  const handleCreateAction = (
    action: Omit<ApprovalAction, 'id' | 'createdAt' | 'status'>
  ) => {
    const newAction: ApprovalAction = {
      ...action,
      id: `act-${Date.now()}`,
      createdAt: new Date().toISOString(),
      status: 'pending',
    };
    setPendingApprovals((prev) => [newAction, ...prev]);
    showToast(`Drafted message for ${action.vendorName}.`);
  };

  const handleDraftInquiryFromVendor = (vendor: VendorPriceRecord) => {
    handleCreateAction({
      actionType: 'send_inquiry',
      vendorName: vendor.vendorName,
      recipientContact: vendor.sourceUrl || 'vendor@example.com',
      draftContent: `Hi ${vendor.vendorName}, we would like to confirm your rate of ${formatInr(
        vendor.basePrice
      )} per ${vendor.unit.replace('per_', '').replace('_', ' ')} for our upcoming event.`,
    });
    setActivePlanTab('checklist');
  };

  // Handlers for Tasks
  const handleUpdateTaskStatus = (taskId: string, status: TimelineTask['status']) => {
    setTasks((prev) =>
      prev.map((t) => (t.id === taskId ? { ...t, status } : t))
    );
  };

  const handleAddTask = (taskData: Omit<TimelineTask, 'id'>) => {
    const newTask: TimelineTask = {
      ...taskData,
      id: `task-${Date.now()}`,
    };
    setTasks((prev) => [...prev, newTask]);
    showToast(`Added task: ${taskData.title}`);
  };

  const handleDeleteTask = (taskId: string) => {
    setTasks((prev) => prev.filter((t) => t.id !== taskId));
  };

  // 1-Click Demo Event Loader
  const handleLoadSampleBatch = () => {
    if (!brief) {
      setBrief(SAMPLE_BRIEFS[0].brief);
    }
    setVendors(SAMPLE_VENDOR_BATCH);
    setTasks(SAMPLE_TASKS_BATCH);
    setPendingApprovals(SAMPLE_APPROVALS_BATCH);
    showToast('Demo event loaded with 6 sample vendors & budget!');
  };

  // Reset to initial clean state
  const handleResetLedger = () => {
    if (window.confirm('Reset all budget data and clear active event?')) {
      setVendors([]);
      setTasks([]);
      setPendingApprovals([]);
      setBrief(null);
      setStructuredPlan(null);
      showToast('Budget reset to clean state.');
    }
  };

  return (
    <div className="min-h-screen bg-[#F8F5EE] text-slate-900 flex flex-col font-sans relative">
      {/* Top Header */}
      <Header
        brief={brief}
        activeViewMode={viewMode}
        onChangeViewMode={(mode) => setViewMode(mode)}
        onOpenInjector={() => setIsInjectorOpen(true)}
        onOpenBriefConfig={() => setViewMode('wizard')}
        onExport={() => setIsExportOpen(true)}
        onReset={handleResetLedger}
        onOpenCommandPalette={() => setIsCommandPaletteOpen(true)}
        onLoadSampleBatch={handleLoadSampleBatch}
        totalRecordsCount={vendors.length}
      />

      {/* Financial Summary KPIs */}
      {brief && <GlobalMetricsBar summary={summary} />}

      {/* Main Workspace */}
      <main className="flex-1 max-w-7xl w-full mx-auto px-4 lg:px-8 py-6">
        {/* =====================================================================
            VIEW MODE 1: SPLIT VIEW (AI Chat on Left + Structured Plan / Table on Right)
        ===================================================================== */}
        {viewMode === 'split' && (
          <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 items-start">
            {/* Left 5 Cols: AI Agent Chat */}
            <div className="lg:col-span-5 sticky top-20 min-w-0 max-w-full">
              <AgentChatPanel
                currentBrief={brief}
                currentVendors={vendors}
                currentStructuredPlan={structuredPlan}
                onPlanGenerated={handlePlanGenerated}
                onStructuredPlanGenerated={handleStructuredPlanGenerated}
                onOpenTableView={() => {
                  setViewMode('split');
                  setActivePlanTab('quotes');
                }}
                onOpenStructuredPlanView={() => {
                  setViewMode('split');
                  setActivePlanTab('structured');
                }}
                onExportPdf={() => setIsExportOpen(true)}
              />
            </div>

            {/* Right 7 Cols: Live Budget Plan & Tables */}
            <div className="lg:col-span-7 space-y-5 min-w-0 max-w-full">
              {!structuredPlan && vendors.length === 0 ? (
                /* Starter Onboarding Card */
                <div className="bg-white border-2 border-black rounded-3xl p-8 sm:p-10 text-center space-y-5 shadow-[6px_6px_0px_0px_#000]">
                  <div className="w-16 h-16 rounded-2xl bg-[#FFE600] border-2 border-black text-black flex items-center justify-center mx-auto text-3xl font-black shadow-[3px_3px_0px_0px_#000]">
                    🎟️
                  </div>
                  <div className="space-y-1.5 max-w-md mx-auto">
                    <h3 className="text-xl sm:text-2xl font-black text-black font-heading tracking-tight uppercase">
                      Start Your Event Planning
                    </h3>
                    <p className="text-xs sm:text-sm font-bold text-slate-700 leading-relaxed">
                      Two ways to plan with one shared deterministic engine: Chat naturally or use our 4-step guided wizard.
                    </p>
                  </div>

                  <div className="flex flex-wrap items-center justify-center gap-3 pt-2">
                    <button
                      onClick={() => setViewMode('wizard')}
                      className="flex items-center gap-2 bg-[#FFE600] hover:bg-[#FACC15] text-black font-black px-5 py-3 rounded-2xl text-xs border-2 border-black shadow-[3px_3px_0px_0px_#000] hover:translate-x-[1px] hover:translate-y-[1px] transition-all"
                    >
                      <Wand2 className="w-4 h-4 stroke-[2.5]" />
                      <span>Launch Guided Wizard</span>
                    </button>

                    <button
                      onClick={handleLoadSampleBatch}
                      className="flex items-center gap-2 bg-[#F8F5EE] hover:bg-slate-100 text-black font-black px-5 py-3 rounded-2xl text-xs border-2 border-black shadow-[2px_2px_0px_0px_#000] hover:translate-x-[1px] hover:translate-y-[1px] transition-all"
                    >
                      <Sparkles className="w-4 h-4 stroke-[2.5]" />
                      <span>Try Sample Demo Plan</span>
                    </button>
                  </div>
                </div>
              ) : (
                <div className="space-y-5">
                  {/* Sub-tab Navigation */}
                  <div className="flex flex-wrap items-center justify-between gap-2 border-b-2 border-black pb-3">
                    <div className="flex items-center gap-1.5 bg-white p-1 rounded-xl border-2 border-black shadow-[2.5px_2.5px_0px_0px_#000]">
                      {structuredPlan && (
                        <button
                          onClick={() => setActivePlanTab('structured')}
                          className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-black transition-all ${
                            activePlanTab === 'structured'
                              ? 'bg-[#FFE600] text-black border-2 border-black shadow-[1.5px_1.5px_0px_0px_#000]'
                              : 'text-slate-700 hover:text-black border-2 border-transparent'
                          }`}
                        >
                          <FileText className="w-3.5 h-3.5 stroke-[2.5]" />
                          <span>Structured Plan</span>
                        </button>
                      )}

                      <button
                        onClick={() => setActivePlanTab('quotes')}
                        className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-black transition-all ${
                          activePlanTab === 'quotes'
                            ? 'bg-[#BAE6FD] text-black border-2 border-black shadow-[1.5px_1.5px_0px_0px_#000]'
                            : 'text-slate-700 hover:text-black border-2 border-transparent'
                        }`}
                      >
                        <Layers className="w-3.5 h-3.5 stroke-[2.5]" />
                        <span>Quotes Ledger ({vendors.length})</span>
                      </button>

                      <button
                        onClick={() => setActivePlanTab('vendors')}
                        className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-black transition-all ${
                          activePlanTab === 'vendors'
                            ? 'bg-[#FFE600] text-black border-2 border-black shadow-[1.5px_1.5px_0px_0px_#000]'
                            : 'text-slate-700 hover:text-black border-2 border-transparent'
                        }`}
                      >
                        <Building2 className="w-3.5 h-3.5 stroke-[2.5]" />
                        <span>Vendor Intelligence</span>
                      </button>

                      <button
                        onClick={() => setActivePlanTab('breakdown')}
                        className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-black transition-all ${
                          activePlanTab === 'breakdown'
                            ? 'bg-[#FEF08A] text-black border-2 border-black shadow-[1.5px_1.5px_0px_0px_#000]'
                            : 'text-slate-700 hover:text-black border-2 border-transparent'
                        }`}
                      >
                        <PieChart className="w-3.5 h-3.5 stroke-[2.5]" />
                        <span>Breakdown</span>
                      </button>

                      <button
                        onClick={() => setActivePlanTab('checklist')}
                        className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-black transition-all ${
                          activePlanTab === 'checklist'
                            ? 'bg-[#D8B4FE] text-black border-2 border-black shadow-[1.5px_1.5px_0px_0px_#000]'
                            : 'text-slate-700 hover:text-black border-2 border-transparent'
                        }`}
                      >
                        <ListTodo className="w-3.5 h-3.5 stroke-[2.5]" />
                        <span>Tasks ({tasks.length})</span>
                      </button>
                    </div>

                    <button
                      onClick={() => setViewMode('plan')}
                      className="text-xs font-black text-black hover:underline flex items-center gap-1"
                    >
                      <span>Full View</span>
                      <ArrowRight className="w-3.5 h-3.5 stroke-[2.5]" />
                    </button>
                  </div>

                  {/* Tab 1: Structured Plan Preview */}
                  {activePlanTab === 'structured' && structuredPlan && (
                    <StructuredPlanPreview
                      plan={structuredPlan}
                      onUpdatePlan={handleUpdateStructuredPlan}
                      onRefinePlan={handleRefineStructuredPlan}
                      isRefining={isRefining}
                      onPlanApproved={handlePlanApproved}
                      onLoadIntoLedger={() => {
                        setActivePlanTab('quotes');
                        showToast('Viewing mapped ledger quotes.');
                      }}
                    />
                  )}

                  {/* Tab 2: Vendor Quotes Table */}
                  {activePlanTab === 'quotes' && (
                    <div className="space-y-5">
                      <VendorLedgerTable
                        vendors={vendors}
                        brief={brief}
                        onToggleSelect={handleToggleSelectVendor}
                        onSelectAll={handleSelectAllVendors}
                        onDeleteVendor={handleDeleteVendor}
                        onOpenAudit={(vendor) => setAuditingVendor(vendor)}
                        onDraftAction={handleDraftInquiryFromVendor}
                        onOpenInjector={() => setIsInjectorOpen(true)}
                        onLoadSampleBatch={handleLoadSampleBatch}
                      />
                      {brief && (
                        <DeterministicScenarioSummary summary={summary} brief={brief} />
                      )}
                    </div>
                  )}

                  {/* Tab 2.5: Vendor Intelligence */}
                  {activePlanTab === 'vendors' && (
                    <VendorDirectoryPanel
                      currentEventId={committedApproval?.event_id}
                      currentBudgetId={committedApproval?.budget_id}
                      onShowToast={showToast}
                    />
                  )}

                  {/* Tab 3: Budget Breakdown */}
                  {activePlanTab === 'breakdown' && (
                    <div className="space-y-5">
                      <DeterministicScenarioSummary summary={summary} brief={brief} />
                    </div>
                  )}

                  {/* Tab 4: Tasks & Inquiries */}
                  {activePlanTab === 'checklist' && (
                    <div className="space-y-5">
                      <TimelineTasksPanel
                        tasks={tasks}
                        vendors={vendors}
                        onUpdateStatus={handleUpdateTaskStatus}
                        onAddTask={handleAddTask}
                        onDeleteTask={handleDeleteTask}
                      />
                      <ApprovalQueuePanel
                        approvals={pendingApprovals}
                        onApprove={handleApproveAction}
                        onReject={handleRejectAction}
                        onCreateAction={handleCreateAction}
                      />
                    </div>
                  )}
                </div>
              )}
            </div>
          </div>
        )}

        {/* =====================================================================
            VIEW MODE 2: CHAT ONLY (Conversational AI Planning)
        ===================================================================== */}
        {viewMode === 'chat' && (
          <div className="max-w-4xl mx-auto space-y-4">
            <AgentChatPanel
              currentBrief={brief}
              currentVendors={vendors}
              currentStructuredPlan={structuredPlan}
              onPlanGenerated={handlePlanGenerated}
              onStructuredPlanGenerated={handleStructuredPlanGenerated}
              onOpenTableView={() => {
                setViewMode('plan');
                setActivePlanTab('quotes');
              }}
              onOpenStructuredPlanView={() => {
                setViewMode('plan');
                setActivePlanTab('structured');
              }}
              onExportPdf={() => setIsExportOpen(true)}
            />
          </div>
        )}

        {/* =====================================================================
            VIEW MODE 3: GUIDED STEP-BY-STEP WIZARD
        ===================================================================== */}
        {viewMode === 'wizard' && (
          <div className="py-2">
            <GuidedPlanningWizard
              onPlanGenerated={(plan) => {
                handleStructuredPlanGenerated(plan);
                setViewMode('plan');
                setActivePlanTab('structured');
              }}
              onCancel={() => setViewMode('split')}
            />
          </div>
        )}

        {/* =====================================================================
            VIEW MODE 4: FULL PLAN PREVIEW ONLY
        ===================================================================== */}
        {viewMode === 'plan' && (
          <div className="space-y-6">
            {structuredPlan ? (
              <StructuredPlanPreview
                plan={structuredPlan}
                onUpdatePlan={handleUpdateStructuredPlan}
                onRefinePlan={handleRefineStructuredPlan}
                isRefining={isRefining}
                onPlanApproved={handlePlanApproved}
                onLoadIntoLedger={() => {
                  setActivePlanTab('quotes');
                  showToast('Viewing mapped ledger quotes.');
                }}
              />
            ) : brief ? (
              /* Fallback if user loaded demo quotes before generating structured plan */
              <div className="space-y-6">
                <div className="flex items-center justify-between border-b-2 border-black pb-3">
                  <div className="flex items-center gap-2">
                    <span className="text-sm font-black text-black">Active Event: {brief.eventName}</span>
                  </div>
                  <button
                    onClick={() => setViewMode('split')}
                    className="flex items-center gap-1.5 text-xs font-black text-black bg-[#FFE600] px-3 py-1.5 rounded-xl border-2 border-black shadow-[2px_2px_0px_0px_#000]"
                  >
                    <Bot className="w-4 h-4" />
                    <span>Open AI Concierge</span>
                  </button>
                </div>
                <VendorLedgerTable
                  vendors={vendors}
                  brief={brief}
                  onToggleSelect={handleToggleSelectVendor}
                  onSelectAll={handleSelectAllVendors}
                  onDeleteVendor={handleDeleteVendor}
                  onOpenAudit={(vendor) => setAuditingVendor(vendor)}
                  onDraftAction={handleDraftInquiryFromVendor}
                  onOpenInjector={() => setIsInjectorOpen(true)}
                  onLoadSampleBatch={handleLoadSampleBatch}
                />
              </div>
            ) : (
              /* Empty state */
              <div className="bg-white border-2 border-black rounded-3xl p-10 max-w-lg mx-auto text-center space-y-4 shadow-[5px_5px_0px_0px_#000]">
                <div className="w-14 h-14 rounded-2xl bg-[#FFE600] border-2 border-black text-black flex items-center justify-center mx-auto text-2xl font-black shadow-[2px_2px_0px_0px_#000]">
                  📋
                </div>
                <h3 className="text-xl font-black text-black font-heading uppercase">
                  No Active Plan Draft Yet
                </h3>
                <p className="text-xs text-slate-700 font-bold leading-relaxed">
                  Start by using the Conversational AI Chat or the Guided 4-Step Wizard to generate a complete structured event plan.
                </p>
                <div className="flex justify-center gap-3 pt-2">
                  <button
                    onClick={() => setViewMode('wizard')}
                    className="bg-[#FFE600] hover:bg-[#FACC15] text-black font-black px-5 py-2.5 rounded-xl text-xs border-2 border-black shadow-[2px_2px_0px_0px_#000] flex items-center gap-1.5 transition-all"
                  >
                    <Wand2 className="w-4 h-4" />
                    <span>Launch Wizard</span>
                  </button>
                  <button
                    onClick={() => setViewMode('chat')}
                    className="bg-[#BAE6FD] hover:bg-[#7DD3FC] text-black font-black px-5 py-2.5 rounded-xl text-xs border-2 border-black shadow-[2px_2px_0px_0px_#000] flex items-center gap-1.5 transition-all"
                  >
                    <Bot className="w-4 h-4" />
                    <span>Launch AI Chat</span>
                  </button>
                </div>
              </div>
            )}
          </div>
        )}

        {/* =====================================================================
            VIEW MODE 5: VENDOR INTELLIGENCE DIRECTORY & COMPARISON
        ===================================================================== */}
        {viewMode === 'vendors' && (
          <div className="space-y-6">
            <VendorDirectoryPanel
              currentEventId={committedApproval?.event_id}
              currentBudgetId={committedApproval?.budget_id}
              onShowToast={showToast}
            />
          </div>
        )}

        {/* =====================================================================
            VIEW MODE 6: EXTERNAL INTELLIGENCE (OSM VENUES DISCOVERY)
        ===================================================================== */}
        {viewMode === 'external' && (
          <div className="space-y-6">
            <ExternalIntelligencePanel
              initialLocation={brief?.location || 'Hyderabad (Banjara Hills)'}
              onSelectForPlanning={(location) => {
                if (brief) {
                  setBrief({ ...brief, location });
                }
                showToast(`Location "${location}" selected for event planning!`);
                setViewMode('wizard');
              }}
              onShowToast={showToast}
            />
          </div>
        )}
      </main>

      {/* Floating Toast Notification */}
      {toastMessage && (
        <div
          role="status"
          aria-live="polite"
          className="fixed bottom-6 right-6 z-50 bg-[#141517] border-2 border-black text-white text-xs font-bold px-4 py-2.5 rounded-xl shadow-[4px_4px_0px_0px_#FFE600] flex items-center gap-2 animate-in fade-in slide-in-from-bottom-2 duration-200"
        >
          <CheckCircle2 className="w-4 h-4 text-[#FFE600] shrink-0" aria-hidden="true" />
          <span>{toastMessage}</span>
        </div>
      )}

      {/* Modals & Drawers */}
      <RecordInjectorModal
        isOpen={isInjectorOpen}
        onClose={() => setIsInjectorOpen(false)}
        onInject={handleInjectRecords}
      />

      <ExportLedgerModal
        isOpen={isExportOpen}
        onClose={() => setIsExportOpen(false)}
        brief={brief}
        vendors={vendors}
        tasks={tasks}
        approvals={pendingApprovals}
        summary={summary}
      />

      <CommandPalette
        isOpen={isCommandPaletteOpen}
        onClose={() => setIsCommandPaletteOpen(false)}
        vendors={vendors}
        onOpenInjector={() => setIsInjectorOpen(true)}
        onOpenBriefConfig={() => setViewMode('wizard')}
        onExport={() => setIsExportOpen(true)}
        onLoadSampleBatch={handleLoadSampleBatch}
        onSelectVendor={(vendor) => setAuditingVendor(vendor)}
      />

      <VerbatimAuditDrawer
        vendor={auditingVendor}
        onClose={() => setAuditingVendor(null)}
      />
    </div>
  );
};

export default App;
